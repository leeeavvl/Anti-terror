"""Транслитерация кириллических маркеров в латиницу — распознаёт слова вроде
«genocide» как то же самое, что «геноцид», написанное латиницей/по-английски
(частый приём обхода фильтров, ищущих только кириллицу).

Схема практическая (как люди реально печатают транслитом), не строгая ГОСТ, и
намеренно даёт НЕСКОЛЬКО вариантов для неоднозначных букв — например «ц» люди
передают то как «ts», то как «c» («геноцид» → «genotsid» ИЛИ «genocid»).
Один и тот же английский корень («genocide») при этом может оказаться ближе
именно ко второму варианту: «genocid» отличается от «genocide» всего на одну
букву (немая «e» на конце), а «genotsid» — уже на несколько. Поэтому
генерируются оба варианта, и точное совпадение конкретной буквы неважно —
дальше подключается тот же нечёткий поиск (fuzzy.py, допуск на 1 опечатку для
слов от 4 букв), который добирает оставшуюся разницу."""

_PRIMARY = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Только буквы, для которых в реальном транслите/английских словах-корнях
# распространён другой вариант написания.
_ALTERNATE = {
    "х": "h",
    "ц": "c",
    "ё": "yo",
    "й": "i",
    "щ": "sch",
    "ю": "iu",
    "я": "ia",
}


def contains_cyrillic(text: str) -> bool:
    return any("а" <= ch.lower() <= "я" or ch.lower() in "ёъь" for ch in text)


def transliterate_variants(text: str) -> list[str]:
    text = text.lower()
    primary = "".join(_PRIMARY.get(ch, ch) for ch in text)
    alternate = "".join(_ALTERNATE.get(ch, _PRIMARY.get(ch, ch)) for ch in text)

    variants = [primary]
    if alternate != primary:
        variants.append(alternate)
    return variants
